#!/usr/bin/env python3
"""generate_site_config.py — prepares the site before `zensical build`.

For every script/config in the repo it generates a page (<file>.md) with a
description, quick facts, download buttons and the full source. It also
generates a home page (index.md), an overview page per folder
(<folder>/index.md) and the nav: section of mkdocs.yml.

Generated files are git-ignored and carry a marker comment, so hand-written
pages with the same name are never overwritten.
"""
from __future__ import annotations

import html
import re
from pathlib import Path

import yaml

REPO = "77777kaz77777/linux-environment-automation"
BRANCH = "main"
RAW_BASE = f"https://raw.githubusercontent.com/{REPO}/{BRANCH}"
BLOB_BASE = f"https://github.com/{REPO}/blob/{BRANCH}"

SITE_TITLE = "Linux Environment Automation"
SITE_TAGLINE = (
    "Scripts and configs for provisioning, updating and hardening Linux "
    "workstations across Fedora, Arch and Debian-based distros."
)

GENERATED_MARKER = "<!-- generated by generate_site_config.py: do not edit -->"

EXCLUDED_DIRS = {".git", ".github", ".obsidian", "site", "assets", "venv", "__pycache__", ".venv", "stylesheets", "node_modules"}
# Repo/site tooling, and personal configs that should not be published
EXCLUDED_FILES = {"generate_site_config.py", "update_links.sh", "gen_pages.py", "AdGuardHome-backup.yaml"}

LANGS = {
    ".sh": ("bash", "Bash"),
    ".py": ("python", "Python"),
    ".toml": ("toml", "TOML"),
    ".conf": ("ini", "Config"),
    ".service": ("ini", "systemd unit"),
    ".timer": ("ini", "systemd timer"),
    ".jsonc": ("json", "JSONC"),
}
RUNNABLE = {".sh", ".py"}

FOLDER_DESCS = {
    "configs": "Dotfiles and app configs: Alacritty, DNF, Fastfetch.",
    "setup-scripts": "Installers that deploy the configs above.",
    "desktop-tweaks": "Desktop and terminal look-and-feel tweaks.",
    "provisioning": "Bootstrap a fresh workstation in one go.",
    "repo-management": "Helpers for organising this repository.",
    "security": "Antivirus, hardening and security references.",
    "updates": "Update and cleanup routines per distro.",
    "utils": "Everyday helpers: VPN toggles, health report, templates.",
}

ACRONYMS = {
    "cli": "CLI", "dns": "DNS", "kde": "KDE", "rog": "ROG", "vpn": "VPN",
    "os": "OS", "osi": "OSI", "clamav": "ClamAV", "dnf": "DNF", "cachyos": "CachyOS",
}
LOWERCASE_WORDS = {"and", "or", "for", "in", "on", "to", "with", "of", "via", "vs"}


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------
def format_label(raw_name: str) -> str:
    words = re.split(r"[-_\s]+", raw_name.strip())
    out = []
    for i, word in enumerate(words):
        low = word.lower()
        if low in ACRONYMS:
            out.append(ACRONYMS[low])
        elif i > 0 and low in LOWERCASE_WORDS:
            out.append(low)
        else:
            out.append(word[:1].upper() + word[1:])
    return " ".join(out)


def _esc(text: str) -> str:
    return html.escape(text, quote=False).replace("[", "&#91;").replace("]", "&#93;")


def is_published(path: Path) -> bool:
    if not path.is_file() or path.suffix not in LANGS or path.name in EXCLUDED_FILES:
        return False
    if path.parent == Path("."):
        return False  # root-level files are repo tooling
    return not any(part.startswith(".") or part in EXCLUDED_DIRS for part in path.parts[:-1])


def scripts_in(directory: Path) -> list[Path]:
    return sorted((p for p in directory.iterdir() if is_published(p)), key=lambda p: p.name.lower())


def sub_dirs(directory: Path) -> list[Path]:
    return sorted(
        (d for d in directory.iterdir() if d.is_dir() and not d.name.startswith(".") and d.name not in EXCLUDED_DIRS),
        key=lambda p: p.name.lower(),
    )


def count_scripts(directory: Path) -> int:
    return len(scripts_in(directory)) + sum(count_scripts(d) for d in sub_dirs(directory))


def describe(path: Path) -> str:
    """Description from the file's header comment (after any shebang)."""
    for raw in path.read_text(encoding="utf-8", errors="ignore").splitlines()[:8]:
        line = raw.strip()
        if not line or line.startswith("#!"):
            continue
        if not line.startswith(("#", "//")):
            break
        text = line.lstrip("#/ ").strip()
        text = re.sub(r"^Description:\s*", "", text, flags=re.IGNORECASE)
        if not text or set(text) <= set("=-*"):
            continue
        text = text.replace("⁠", "")
        return text[0].upper() + text[1:]
    return ""


def needs_root(path: Path) -> bool:
    if path.suffix != ".sh":
        return False
    text = path.read_text(encoding="utf-8", errors="ignore")
    return bool(re.search(r"EUID|\bsudo\b|id -u\)?\" -ne 0", text))


def _write_generated(path: Path, body: str) -> None:
    if path.exists() and GENERATED_MARKER not in path.read_text(encoding="utf-8", errors="ignore"):
        print(f"Skipping {path}: it exists and was not generated by this script")
        return
    path.write_text(body, encoding="utf-8")


# ---------------------------------------------------------------------------
# Pages
# ---------------------------------------------------------------------------
def write_script_page(path: Path) -> None:
    rel = path.as_posix()
    lang, lang_label = LANGS[path.suffix]
    desc = describe(path)
    lines = path.read_text(encoding="utf-8", errors="ignore").count("\n") + 1

    chips = [lang_label, f"{lines} lines", f"{path.parent.as_posix()}/"]
    chip_html = "".join(f'<span class="kz-chip">{_esc(c)}</span>' for c in chips)
    if needs_root(path):
        chip_html += '<span class="kz-chip kz-chip--warn">Needs root</span>'

    parts = [
        "---",
        f'title: "{path.name}"',
        "---",
        "",
        GENERATED_MARKER,
        "",
        f"# {path.name}",
        "",
    ]
    if desc:
        parts += [desc, ""]
    parts += [
        f'<div class="kz-meta">{chip_html}</div>',
        "",
        '<div class="kz-actions" markdown>',
        f"[Raw file]({RAW_BASE}/{rel}){{ .md-button .md-button--primary }}",
        f"[View on GitHub]({BLOB_BASE}/{rel}){{ .md-button }}",
        "</div>",
        "",
    ]

    if path.suffix in RUNNABLE:
        runner = "python3" if path.suffix == ".py" else ("sudo bash" if needs_root(path) else "bash")
        parts += [
            "## Quick start",
            "",
            "```bash",
            f"curl -fsSLO {RAW_BASE}/{rel}",
            f"less {path.name}   # read it first",
            f"{runner} {path.name}",
            "```",
            "",
        ]

    parts += [
        "## Source",
        "",
        f'````{lang} title="{rel}" linenums="1"',
        f'--8<-- "{rel}"',
        "````",
        "",
    ]
    _write_generated(path.with_name(path.name + ".md"), "\n".join(parts))


def _list_item(path: Path, href: str) -> str:
    desc = describe(path)
    desc_html = f'<span class="kz-list__desc">{_esc(desc)}</span>' if desc else ""
    return f'- [<span class="kz-list__title">{_esc(path.name)}</span>{desc_html}]({href})'


def _card(directory: Path, href: str) -> str:
    n = count_scripts(directory)
    noun = "file" if n == 1 else "files"
    return (
        f'[<span class="kz-card__title">{_esc(format_label(directory.name))}'
        f'<span class="kz-card__count">{n} {noun}</span></span>'
        f'<span class="kz-card__desc">{_esc(FOLDER_DESCS.get(directory.name, ""))}</span>]({href}){{ .kz-card }}'
    )


def write_folder_page(directory: Path) -> None:
    title = format_label(directory.name)
    parts = [
        "---",
        f'title: "{title}"',
        "hide:",
        "  - toc",
        "---",
        "",
        GENERATED_MARKER,
        '<span class="kz-generated"></span>',
        "",
        f"# {title}",
        "",
    ]
    if directory.name in FOLDER_DESCS:
        parts += [FOLDER_DESCS[directory.name], ""]

    scripts = scripts_in(directory)
    if scripts:
        parts += ['<div class="kz-list" markdown>', ""]
        parts += [_list_item(p, p.name + ".md") for p in scripts]
        parts += ["", "</div>", ""]

    subs = [d for d in sub_dirs(directory) if count_scripts(d)]
    if subs:
        parts += ["## Subfolders", "", '<div class="kz-cards" markdown>', ""]
        for d in subs:
            parts += [_card(d, f"{d.name}/index.md"), ""]
        parts += ["</div>", ""]

    _write_generated(directory / "index.md", "\n".join(parts))
    for d in subs:
        write_folder_page(d)


def write_home_page(folders: list[Path]) -> None:
    total = sum(count_scripts(d) for d in folders)
    cards = "\n\n".join(_card(d, f"{d.name}/index.md") for d in folders)
    body = f"""---
title: Home
hide:
  - navigation
  - toc
---

{GENERATED_MARKER}
<span class="kz-generated"></span>

<div class="kz-hero" markdown>

# {SITE_TITLE}

{SITE_TAGLINE}

<div class="kz-stats" markdown>
<span class="kz-stat"><strong>{total}</strong> scripts &amp; configs</span>
<span class="kz-stat"><strong>{len(folders)}</strong> folders</span>
<span class="kz-stat kz-stat--keys">Press <strong>/</strong> to search</span>
</div>

</div>

## Browse

<div class="kz-cards" markdown>

{cards}

</div>

## Grab a single script

Every page has a **Raw file** button and a copy-paste quick start. To pick a script interactively from a terminal:

```bash
curl -fsSLO {RAW_BASE}/utils/pull-script.sh
bash pull-script.sh
```

!!! warning "Read before you run"
    Many of these scripts change system settings and need root. Open the page,
    skim the source, and keep a snapshot or backup handy.
"""
    _write_generated(Path("index.md"), body)


# ---------------------------------------------------------------------------
# Navigation and housekeeping
# ---------------------------------------------------------------------------
def build_nav(directory: Path) -> list:
    nav: list = [f"{directory.as_posix()}/index.md"]
    for p in scripts_in(directory):
        nav.append({p.name: f"{p.as_posix()}.md"})
    for d in sub_dirs(directory):
        if count_scripts(d):
            nav.append({format_label(d.name): build_nav(d)})
    return nav


def update_gitignore() -> None:
    gitignore_path = Path(".gitignore")
    entries = [f"*{ext}.md" for ext in LANGS] + ["/index.md", "*/index.md", "*/*/index.md", "site/"]
    content = gitignore_path.read_text(encoding="utf-8") if gitignore_path.exists() else ""
    existing = set(content.splitlines())
    appends = [e for e in entries if e not in existing]
    if appends:
        with open(gitignore_path, "a", encoding="utf-8") as f:
            f.write("\n# Generated by generate_site_config.py\n" + "\n".join(appends) + "\n")


def main() -> None:
    update_gitignore()

    folders = [d for d in sub_dirs(Path(".")) if count_scripts(d)]
    for path in Path(".").rglob("*"):
        if is_published(path):
            write_script_page(path)
    for d in folders:
        write_folder_page(d)
    write_home_page(folders)

    mkdocs_path = Path("mkdocs.yml")
    config = yaml.safe_load(mkdocs_path.read_text(encoding="utf-8"))
    config["nav"] = [{"Home": "index.md"}] + [{format_label(d.name): build_nav(d)} for d in folders]
    mkdocs_path.write_text(
        yaml.dump(config, default_flow_style=False, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    print(f"Generated pages for {sum(count_scripts(d) for d in folders)} files in {len(folders)} folders")


if __name__ == "__main__":
    main()
